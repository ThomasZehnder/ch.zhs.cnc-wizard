def dxf_lwpolyline(points_with_bulge):
    """Generate an LWPOLYLINE entity with bulge for arcs"""
    entity = f"""  0
LWPOLYLINE
  8
0
 70
1
 90
{len(points_with_bulge)}
"""
    for x, y, bulge in points_with_bulge:
        entity += f""" 10
{x}
 20
{y}
 42
{bulge}
"""
    return entity

def dxf_footer():
    """Generate DXF footer"""
    return """  0
ENDSEC
  0
EOF
"""

# Circle: 160mm diameter (80mm radius)
circle_radius = 80

# Square: 35mm x 35mm, corner radius 10mm
square_size = 35
corner_radius = 10
half_square = square_size / 2

# Positions for 4 squares (0°, 90°, 180°, 270°)
radius_to_center = circle_radius + half_square
positions = [
    (0, radius_to_center),              # 0° = top
    (radius_to_center, 0),              # 90° = right
    (0, -radius_to_center),             # 180° = bottom
    (-radius_to_center, 0),             # 270° = left
]

# Generate DXF content
dxf_content = dxf_header()

# Add circle
dxf_content += dxf_circle(0, 0, circle_radius)

# Add 4 rounded squares
for cx, cy in positions:
    # Calculate bulge for rounded corners
    bulge = math.tan(math.radians(45)) * (corner_radius / half_square)

    corners = [
        (cx - half_square, cy - half_square),  # bottom-left
        (cx + half_square, cy - half_square),  # bottom-right
        (cx + half_square, cy + half_square),  # top-right
        (cx - half_square, cy + half_square),  # top-left
    ]

    points = [(x, y, bulge) for x, y in corners]
    dxf_content += dxf_lwpolyline(points)

dxf_content += dxf_footer()

# Write to file
output_path = r'd:\Arduino\force-sensor\messplatte-ir-160-p\messplatte.dxf'
with open(output_path, 'w') as f:
    f.write(dxf_content)

